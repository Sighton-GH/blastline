import { chromium } from 'playwright';
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
const ROOT = '/home/sandbox/blastline';
const MIME = new Map([['.css','text/css'],['.html','text/html'],['.js','text/javascript'],['.mjs','text/javascript'],['.webp','image/webp'],['.png','image/png']]);
const server = http.createServer((req,res)=>{ const p=decodeURIComponent(new URL(req.url,'http://x').pathname).replace(/^\/+/,''); const f=path.resolve(ROOT,p===''?'index.html':p); fs.readFile(f,(e,d)=>{ if(e){res.writeHead(404);return res.end();} res.writeHead(200,{'Cache-Control':'no-store','Content-Type':MIME.get(path.extname(f))||'application/octet-stream'}); res.end(d); }); });
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const port = server.address().port;
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 844, height: 390 }, hasTouch: true, isMobile: true });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await page.goto(`http://127.0.0.1:${port}/?qa&diff=veteran`, { waitUntil: 'load' });
await page.waitForTimeout(700);
await page.screenshot({ path: '/home/sandbox/c6-evidence/v2-land-home.png' });
await page.evaluate(() => { const b = document.querySelectorAll('#difficultyPicker button'); if (b[1]) b[1].click(); });
await page.waitForTimeout(150); await page.tap('#playBtn'); await page.waitForTimeout(400);
await page.evaluate(() => {
  __blastlineTest.setBuild({ power: 2, fireRate: 6, projectiles: 2, pierce: 1, plating: 2 });
  __blastlineTest.setTroops(28); __blastlineTest.setWave(5);
  const st = __blastlineTest.advance(6);
  console.log('LAND-KV', JSON.stringify({ wave: st.wave, killViz: st.killViz && { kills: st.killViz.kills, onScreen: st.killViz.onScreen, mean: +(st.killViz.visibleSum/Math.max(1,st.killViz.kills)).toFixed(2) } }));
});
await page.waitForTimeout(200);
await page.screenshot({ path: '/home/sandbox/c6-evidence/v2-land-melt.png' });
const arm = await page.evaluate(() => { __blastlineTest.setWaveTime(__blastlineTest.getWaveConfig().duration + 1); __blastlineTest.advance(0.3); return __blastlineTest.getState().state; });
await page.waitForTimeout(200);
await page.screenshot({ path: '/home/sandbox/c6-evidence/v2-land-armory.png' });
console.log('ARMORY-STATE', arm, 'cards', await page.evaluate(() => document.querySelectorAll('#rewardCards .reward-card').length));
await page.evaluate(() => { const b = document.querySelector('.armory-continue'); if (b && !b.disabled) b.click(); });
await page.waitForTimeout(250);
const boss = await page.evaluate(() => {
  __blastlineTest.setWave(6);
  __blastlineTest.setWaveTime(__blastlineTest.getWaveConfig().duration + 1);
  __blastlineTest.advance(0.2); __blastlineTest.setWaveTime(0); __blastlineTest.advance(3.4);
  const st = __blastlineTest.getState();
  return { state: st.state, archetype: st.bossArchetype, bossY: st.boss && +st.boss.y.toFixed(2) };
});
console.log('BOSS', JSON.stringify(boss));
await page.waitForTimeout(200);
await page.screenshot({ path: '/home/sandbox/c6-evidence/v2-land-boss.png' });
console.log('JS ERRORS:', errors.length ? errors.slice(0,3) : 'none');
await browser.close(); server.close(); process.exit(0);
